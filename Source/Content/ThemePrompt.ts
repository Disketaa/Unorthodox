/** The prompt a host hands to an assistant to have a theme written for them. A file of its own
 * rather than a string among the interface wording: it is never said on screen, it is copied
 * out and run elsewhere. `{ТЕМА}` is where the theme goes, left standing when there is none. */
export const ThemePromptTemplate = `Ты придумываешь задания для party-игры «Нестандартненько».

ПРАВИЛА ИГРЫ
Все игроки (до 12) одновременно пишут короткий ответ на вопрос.
Очки получают те, чьи ответы совпали. Поэтому хороший вопрос такой,
что у большинства людей в голове всплывает один из 4-8 одинаковых
ответов (голова), но при этом существует минимум 12 разных допустимых
ответов (хвост), чтобы никого не заставлять повторять чужой.

ЗАДАЧА
Тема: {ТЕМА}
Придумай от 10 до 15 заданий по этой теме и выдай JSON.
Чем больше сильных вопросов, тем лучше, но минимум 10.
Расставь вопросы от самых сильных к самым слабым.
Не снижай планку ради количества: если хороших вопросов не хватает,
расширяй категории, а не пиши слабые.

ЭТАП 1. РАЗВЕДКА (если у тебя есть доступ к поиску)
Перед написанием вопросов сделай 3-6 поисковых запросов, чтобы
понять, какие ассоциации и категории существуют вокруг темы.
Примеры запросов (подставь тему):
- «топ 10 вещей, связанных с {ТЕМА}»
- «за что известно: {ТЕМА}»
- «с чем ассоциируется {ТЕМА}»
- «{ТЕМА} известные люди / места / предметы»
- «{ТЕМА} в фильмах, играх, сериалах, мемах»
- «{ТЕМА} популярные вопросы викторины»
Цель разведки: собрать список ШИРОКИХ категорий и популярных
ассоциаций, а не нишевых фактов. Результаты поиска — материал для
идей, а не готовые вопросы: не копируй формулировки из найденного
и не бери факты, которые знают только энтузиасты темы.
Дополнительно можно поискать «список {категория}», чтобы убедиться,
что у выбранной категории есть 12 разных ответов.
Если поиска нет, пропусти этап и опирайся на свои знания.

ЭТАП 2. ТРЕБОВАНИЯ К ВОПРОСАМ
1. Ответ состоит из 1-3 слов.
2. Голова: 4-8 очевидных ответов. Хвост: минимум 12 допустимых.
   Перед выдачей мысленно назови 12 разных ответов на каждый вопрос.
   Если застрял на 8-м, вопрос слишком узкий: расширь или замени.
3. ШИРИНА КАТЕГОРИИ. Тема уже сужает контекст, поэтому категория
   вопроса должна быть широкой. Не добавляй второй фильтр поверх
   темы. Плохо: «Часть доспеха рыцаря». Хорошо: «Оружие рыцаря».
   Если вопрос является подкатегорией другого вопроса, оставь
   только широкий вариант.
4. Формулировка нейтральная, как строчка из справочника. Якорь
   уточняет категорию через статус, класс или происхождение.
5. ЗАПРЕЩЕНО: выдуманные сцены и бытовые детали («который грызут
   перед телевизором», «которую ели крестьяне»), глаголы-команды
   («Назовите», «Перечислите»), вопросы с ответом-предложением,
   вопросы, где есть 2-3 очевидных ответа и больше ничего
   (например «Лаунчер а-ля Steam»).
6. Не нужны слишком нишевые знания: вопрос должен быть понятен
   компании из 6-7 обычных людей.

РАЗНООБРАЗИЕ
- Не больше 2 вопросов с одной и той же конструкцией и не больше
  2 вопросов, начинающихся с одного слова, на весь список.
- Слово темы («средневековый» и т.п.) можно использовать не более
  чем в 3 вопросах. В остальных тема должна читаться из контекста
  или из самих ответов.
- Каждый вопрос из своего типа. Выбирай разные: люди, места,
  предметы, животные, еда, события, фильмы/игры/книги по теме,
  понятия.
- Не должно быть двух вопросов, у которых почти совпадают ответы
  (король и монарх).
- Распределение: примерно 70% прямых и 30% мемных или из
  поп-культуры (в духе «Игра, в которой вспоминают "мам"»,
  «Предметы из этой игры дороже самой игры»). Минимум 3 вопроса из
  10 мемные или из поп-культуры. Они тоже должны проходить проверку
  головы и хвоста.

ПРИМЕРЫ (только для понимания стиля, НЕ копируй конструкции и
не используй их как шаблон, даже если они подходят к теме)
Игра про автоматизацию
Ко-оп хоррор из Steam
Игра с пиксельной графикой
Игра, в которой вспоминают «мам»
Предметы из этой игры дороже самой игры
Что можно приготовить из теста
Название лапши быстрого приготовления
Бренд энергетического напитка
Блюдо на новогодний стол
Продукт с высоким содержанием белка
Фрукт семейства «цитрусовые»
Разновидность ореха

ПРОВЕРКА ПЕРЕД ВЫВОДОМ
Пройди по списку и убери дубли, вопросы с коротким хвостом и
повторяющиеся конструкции. Если после этого осталось меньше 10,
добавь вопросы других типов.

ЦВЕТ
Выбери один цвет, подходящий по настроению теме, строго из списка:
Coral, Amber, Yellow, Lime, Mint, Sky, Violet, Rose

ФОРМАТ ВЫВОДА
Только JSON, без пояснений, без markdown и без описания поиска:
{
  "name": <>
  "color": "<один из 8 цветов>",
  "questions": [
    "...",
    "..."
  ]
}`;

/** The prompt with the theme's name put in, or with the placeholder left standing when there is
 * no name to put there. Every occurrence is filled, not only the first: the same word stands in
 * the task line and again in each of the example searches. */
export function themePrompt(theme: string | undefined): string {
  const name = theme?.trim();
  return name === undefined || name.length === 0
    ? ThemePromptTemplate
    : ThemePromptTemplate.split('{ТЕМА}').join(name);
}
