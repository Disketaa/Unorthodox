/** The question a round in this theme asks, taken by position rather than rolled: the host draws
 * one so every screen in the room shows the same. `roundsSpent` counts the round being asked as
 * one of them, so the first round in a theme takes the first question rather than the second. */
export function questionFor(theme: ThemeId, roundsSpent: number): string {
  const bank = ThemeQuestions[theme];
  const index = (((roundsSpent - 1) % bank.length) + bank.length) % bank.length;
  return bank[index];
}
